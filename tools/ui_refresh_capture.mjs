import { createRequire } from 'node:module';
const require=createRequire(new URL('../frontend/package.json',import.meta.url));
const {chromium}=require('@playwright/test');
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
await page.goto('http://127.0.0.1:8501');
await page.getByRole('textbox',{name:'Message Student Compass'}).waitFor();
await page.evaluate(()=>document.fonts.ready);
await page.screenshot({path:'reports/ui-refresh-desktop.png',fullPage:true,animations:'disabled'});
console.log('desktop overflow',await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
const mobile=await browser.newPage({viewport:{width:390,height:844}});
await mobile.goto('http://127.0.0.1:8501');
await mobile.getByRole('textbox',{name:'Message Student Compass'}).waitFor();
await mobile.evaluate(()=>document.fonts.ready);
await mobile.screenshot({path:'reports/ui-refresh-mobile.png',fullPage:true,animations:'disabled'});
console.log('mobile overflow',await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
await page.emulateMedia({reducedMotion:'reduce'});
console.log('reduced motion',await page.locator('.welcome').evaluate(el=>getComputedStyle(el).animationName));
await browser.close();
